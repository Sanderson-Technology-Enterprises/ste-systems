import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import jsdoc2md from "jsdoc-to-markdown";
import { format } from "prettier";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modules = [
  "app/data/studio-scenarios.ts",
  "app/lib/website-templates.ts",
  "app/lib/design-plan.ts",
  "app/lib/design-sharing.ts",
  "app/lib/preview-protocol.ts",
  "app/lib/contrast.ts",
  "app/lib/inspector-state.ts",
  "app/components/DesignPlanProvider.tsx",
  "app/components/studio/PreviewFrame.tsx",
  "app/components/studio/ScenarioRenderer.tsx",
  "app/components/studio/LegacyScenarioRenderer.tsx",
  "app/components/studio/WebsiteTemplateGallery.tsx",
  "app/components/studio/scenarios/ScenarioScaffold.tsx",
  "app/components/studio/scenarios/MarketingTemplate.tsx",
  "app/components/studio/scenarios/StorefrontTemplate.tsx",
  "app/components/studio/scenarios/NewsletterTemplate.tsx",
  "app/components/studio/scenarios/BlogTemplate.tsx",
  "app/components/studio/scenarios/IndustrialTemplate.tsx",
  "app/components/studio/scenarios/InventoryTemplate.tsx",
  "app/components/studio/StudioReferences.tsx",
  "app/components/LabWorkbench.tsx",
  "app/components/WorkbenchInspector.tsx",
];
const check = process.argv.includes("--check");
let drift = false;

/** Generate one stable jsdoc2md page per public studio module. */
for (const entry of modules) {
  const source = await readFile(path.join(root, entry), "utf8");
  const javascript = ts.transpileModule(source, {
    fileName: entry,
    compilerOptions: {
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
      jsx: ts.JsxEmit.ReactJSX,
      removeComments: false,
    },
  }).outputText;
  const temporary = path.join(
    root,
    ".tmp",
    "studio-docs",
    path.basename(entry).replace(/\.tsx?$/, ".js"),
  );
  await mkdir(path.dirname(temporary), { recursive: true });
  await writeFile(temporary, javascript);
  const rendered = await jsdoc2md.render({
    files: temporary,
    EOL: "posix",
    "no-cache": true,
  });
  const formatted = await format(
    `<!-- Generated by scripts/generate-studio-docs.mjs; edit JSDoc in ${entry}. -->\n# ${path.basename(entry, path.extname(entry))}\n\n${rendered.trim()}\n`,
    { parser: "markdown", endOfLine: "lf" },
  );
  /** JSDoc hard-break padding is unnecessary before blank lines and fails diff checks. */
  const output = formatted.replace(/[\t ]+$/gm, "");
  const target = path.join(
    root,
    "docs",
    "api",
    "studio",
    path.basename(entry).replace(/\.tsx?$/, ".md"),
  );
  if (check) {
    try {
      if ((await readFile(target, "utf8")) !== output) drift = true;
    } catch {
      drift = true;
    }
  } else {
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, output);
  }
}
if (check && drift) {
  console.error(
    "Studio API documentation has drifted. Run npm run docs:generate.",
  );
  process.exitCode = 1;
}
